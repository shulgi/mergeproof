/** Records whose address is printed on the lines after a bare "Address:" label. */
const FOLLOWING_LINE_ADDRESS = new Set(['KX 9']);

const HEADER = ["Northlight Members' Studio", 'Annual statement 2026'];
const FOOTER = 'Synthetic sample. All names and addresses are invented.';
const CLEAN_ORDER = ['KX 9', '00042', 'Ö-17', 'a-0310', '00107', 'A-0310'];

export function buildCsv(columns, rows, { bom = true, eol = '\r\n' } = {}) {
  const lines = [
    columns.map(csvCell).join(','),
    ...rows.map((row) => columns.map((column) => csvCell(row[column] ?? '')).join(',')),
  ];
  return `${bom ? BOM : ''}${lines.join(eol)}${eol}`;
}

function csvCell(value) {
  const text = String(value);
  return /[",\r\n]/.test(text) || text !== text.trim() ? `"${text.replaceAll('"', '""')}"` : text;
}

export function sampleCsv() {
  return buildCsv(SAMPLE_COLUMNS, SAMPLE_ROWS);
}

function coverLines() {
  return [
    HEADER[0],
    'Annual statements, synthetic merge sample',
    '',
    'This file was generated by the MergeProof fixture script.',
    'Every person, address and amount in it is invented.',
  ];
}

/** Lines of one record page in map order: ID line, field lines, end marker. */
export function recordLines(row, { replace = {}, omit = [], end = true } = {}) {
  const id = row['Member ID'];
  const lines = [...HEADER, '', `${SAMPLE_MAP.idLabel} ${id}`];
  for (const field of SAMPLE_MAP.fields) {
    if (omit.includes(field.column)) continue;
    const valueLines = String(replace[field.column] ?? row[field.column]).split('\n');
    if (field.column === 'Mailing Address' && FOLLOWING_LINE_ADDRESS.has(id)) {
      lines.push(field.label, ...valueLines);
    } else {
      lines.push(`${field.label} ${valueLines[0]}`, ...valueLines.slice(1));
    }
  }
  if (end) lines.push(SAMPLE_MAP.endMarker);
  lines.push('', FOOTER);
  return lines;
}

function rowsById() {
  return new Map(SAMPLE_ROWS.map((row) => [row['Member ID'], row]));
}

/** Cover page plus every CSV record once, in a different order from the CSV. */
export function cleanProofPages() {
  const byId = rowsById();
  return [coverLines(), ...CLEAN_ORDER.map((id) => recordLines(byId.get(id)))];
}

/**
 * Deliberately broken proof (physical page numbers):
 *   1 cover page (no record; not a finding)
 *   2 "00042" with a wrong Balance
 *   3 "00107" without its Postcode line
 *   4 "A-0310" correct
 *   5 "A-0310" again (duplicate PDF ID)
 *   6 "Z-999", which is not in the CSV
 *   7 blank page (no extractable text)
 *   8 "KX 9" without the end marker (invalid boundary)
 *   9 "Ö-17" with a second "Member ID: a-0310" line (ambiguous)
 * so "a-0310", "KX 9" and "Ö-17" are never verified and are reported missing.
 */
export function brokenProofPages() {
  const byId = rowsById();
  const ambiguous = recordLines(byId.get('Ö-17'));
  ambiguous.splice(ambiguous.indexOf(SAMPLE_MAP.endMarker), 0, `${SAMPLE_MAP.idLabel} a-0310`);
  return [
    coverLines(),
    recordLines(byId.get('00042'), { replace: { Balance: '€1,205.00' } }),
    recordLines(byId.get('00107'), { omit: ['Postcode'] }),
    recordLines(byId.get('A-0310')),
    recordLines(byId.get('A-0310')),
    recordLines(UNKNOWN_ROW),
    [],
    recordLines(byId.get('KX 9'), { end: false }),
    ambiguous,
  ];
}

export const SAMPLE_FILES = Object.freeze({
  map: 'map.json',
  csv: 'records.csv',
  cleanPdf: 'proof-clean.pdf',
  brokenPdf: 'proof-broken.pdf',
});

/** Write the four sample files into `outDir` (created if needed; these four files are overwritten). */
export async function writeSamples(outDir) {
  await mkdir(outDir, { recursive: true });
  const paths = Object.fromEntries(Object.entries(SAMPLE_FILES).map(([key, name]) => [key, join(outDir, name)]));
  await writeFile(paths.map, `${JSON.stringify(SAMPLE_MAP, null, 2)}\n`, 'utf8');
  await writeFile(paths.csv, sampleCsv(), 'utf8');
  await writeFile(paths.cleanPdf, buildPdf(cleanProofPages(), { title: 'MergeProof sample: clean proof' }));
  await writeFile(paths.brokenPdf, buildPdf(brokenProofPages(), { title: 'MergeProof sample: broken proof' }));
  return paths;
}
